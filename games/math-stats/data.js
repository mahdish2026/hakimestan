  function checkAnswer(task, userValue, labState) {
    if (task.kind === 'choice') {
      return Number.isInteger(userValue) && userValue === task.answer;
    }
    const n = normNum(userValue);
    if (n === null || !closeEq(n, task.answer)) return false;
    if (task.kind === 'lab' && labState) {
      if (task.labType === 'line') {
        const pts = labState.points || [];
        if (pts.length !== task.targetPoints.length || pts.some((v, i) => v !== task.targetPoints[i])) {
          return 'lab-incomplete';
        }
      } else if (task.labType === 'level') {
        if (!labState.leveled) return 'lab-incomplete';
      } else if (task.labType === 'spinner') {
        const blueCount = (labState.slices || []).filter((c) => c === 'blue').length;
        const greenCount = (labState.slices || []).filter((c) => c === 'green').length;
        if (blueCount !== task.targetBlue || greenCount !== task.targetGreen) {
          return 'lab-incomplete';
        }
      }
    }
    return true;
  }

